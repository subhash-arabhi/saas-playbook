#!/usr/bin/env node
// Exports the DESIGN.md tokens that `design.md export` drops (motion, zIndex, breakpoints, iconSize) as a
// Tailwind v4 @theme block. Import the file after the design.md export in the global CSS.
//   node .agents/tools/design-tokens.mjs [DESIGN.md] [--out <file>]    default: DESIGN.md, print to stdout
//   node .agents/tools/design-tokens.mjs [DESIGN.md] --json            the same tokens as JSON (for Motion springs in JS)
import { readFileSync, writeFileSync, realpathSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

export const GROUPS = ['motion', 'zIndex', 'breakpoints', 'iconSize']

/** The extra token groups from a DESIGN.md's front matter: { motion: { name: value }, … }. Missing groups are empty. */
export function extraTokens(text) {
  const front = text.match(/^---\n([\s\S]*?)\n---\n/)
  if (!front) throw new Error('DESIGN.md has no front matter')
  const out = Object.fromEntries(GROUPS.map((g) => [g, {}]))
  let group = null
  for (const line of front[1].split('\n')) {
    const top = line.match(/^([A-Za-z][\w-]*):\s*(#.*)?$/)
    if (top || /^\S/.test(line)) {
      group = top && GROUPS.includes(top[1]) ? top[1] : null
      continue
    }
    const kv = group && line.match(/^ {2}([\w-]+):\s*(.+?)\s*(?:#.*)?$/)
    if (kv) out[group][kv[1]] = kv[2].replace(/^"(.*)"$/, '$1').replace(/^'(.*)'$/, '$1')
  }
  return out
}

/** CSS custom property name per group, in Tailwind v4's theme namespaces where one exists. */
function cssName(group, name) {
  if (group === 'motion') {
    if (name.startsWith('ease-')) return `--${name}`
    if (name.startsWith('duration-')) return `--${name}`
    return `--motion-${name}`
  }
  if (group === 'zIndex') return `--z-${name}`
  if (group === 'breakpoints') return `--breakpoint-${name}`
  return `--spacing-icon-${name}`
}

export function themeCss(tokens) {
  const lines = ['/* Generated by .agents/tools/design-tokens.mjs from DESIGN.md. Do not edit. */', '@theme {']
  for (const group of GROUPS) for (const [name, value] of Object.entries(tokens[group])) lines.push(`  ${cssName(group, name)}: ${value};`)
  lines.push('}')
  return `${lines.join('\n')}\n`
}

function main(args) {
  const json = args.includes('--json')
  const outAt = args.indexOf('--out')
  const out = outAt >= 0 ? args[outAt + 1] : null
  if (outAt >= 0 && !out) {
    console.error('usage: design-tokens.mjs [DESIGN.md] [--out <file> | --json]')
    return 2
  }
  const file = args.find((a, i) => !a.startsWith('--') && (outAt < 0 || i !== outAt + 1)) || 'DESIGN.md'
  let tokens
  try {
    tokens = extraTokens(readFileSync(file, 'utf8'))
  } catch (e) {
    console.error(`${file}: ${e.message}`)
    return 1
  }
  const text = json ? `${JSON.stringify(tokens, null, 2)}\n` : themeCss(tokens)
  if (out) writeFileSync(out, text)
  else process.stdout.write(text)
  return 0
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(resolve(process.argv[1]))).href) {
  process.exitCode = main(process.argv.slice(2))
}
